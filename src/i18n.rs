use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Language {
    English,
    Indonesian,
    Japanese,
    Dutch,
    Spanish,
    Arabic,
}

impl Default for Language {
    fn default() -> Self {
        Language::English
    }
}

impl Language {
    pub fn code(&self) -> &'static str {
        match self {
            Language::English => "en",
            Language::Indonesian => "id",
            Language::Japanese => "ja",
            Language::Dutch => "nl",
            Language::Spanish => "es",
            Language::Arabic => "ar",
        }
    }

    #[allow(dead_code)]
    pub fn display_name(&self) -> &'static str {
        match self {
            Language::English => "English (EN)",
            Language::Indonesian => "Bahasa Indonesia (ID)",
            Language::Japanese => "日本語 (JA)",
            Language::Dutch => "Nederlands (NL)",
            Language::Spanish => "Español (ES)",
            Language::Arabic => "العربية (AR)",
        }
    }

    pub fn toggle(&self) -> Self {
        match self {
            Language::English => Language::Indonesian,
            Language::Indonesian => Language::Japanese,
            Language::Japanese => Language::Dutch,
            Language::Dutch => Language::Spanish,
            Language::Spanish => Language::Arabic,
            Language::Arabic => Language::English,
        }
    }

    pub fn from_code(code: &str) -> Self {
        match code {
            "id" => Language::Indonesian,
            "ja" => Language::Japanese,
            "nl" => Language::Dutch,
            "es" => Language::Spanish,
            "ar" => Language::Arabic,
            _ => Language::English,
        }
    }
}

